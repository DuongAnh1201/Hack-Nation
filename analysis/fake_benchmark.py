"""Generate a FAKE results/benchmark.json in the shared contract, for building and testing
the analysis and the UI before Person 1's real runs exist.

The file is stamped "_fake": true; every output made from it says FAKE DATA.
Never use it for a claim.

Run:  python -m analysis.fake_benchmark --out analysis/fixtures/fake_benchmark.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

# (success probability, median evaluations when successful) per method: invented, illustrative only
PROFILES = {
    "random": (0.4, 1500),
    "bayes_opt": (0.8, 850),
    "agent_lab": (0.9, 330),
    "agent_lab_no_feedback": (0.7, 700),
}


def make_fake(seeds: int = 10, budget: int = 2000, target: float = 55.0, seed: int = 8) -> dict:
    rng = np.random.default_rng(seed)
    methods = {}
    for name, (p_success, median) in PROFILES.items():
        evals, best = [], []
        for _ in range(seeds):
            e = int(round(median * float(rng.lognormal(0.0, 0.45))))
            if rng.random() < p_success and 1 <= e <= budget:
                evals.append(e)
                best.append(round(target + abs(float(rng.normal(1.5, 1.0))), 2))
            else:
                evals.append(None)
                best.append(round(target - abs(float(rng.normal(2.0, 1.5))) - 0.01, 2))
        methods[name] = {"evals_to_target": evals, "best_w_m2": best}
    return {
        "_fake": True,
        "_note": "FAKE DATA generated by analysis/fake_benchmark.py for development. Not results.",
        "target_w_m2": target,
        "budget": budget,
        "seeds": seeds,
        "methods": methods,
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m analysis.fake_benchmark", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="analysis/fixtures/fake_benchmark.json")
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--budget", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=8)
    args = ap.parse_args(argv)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(make_fake(args.seeds, args.budget, seed=args.seed), indent=2), encoding="utf-8")
    print(f"wrote FAKE benchmark to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
